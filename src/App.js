import React, { Fragment, useEffect, useState } from "react";
// import "bootstrap/dist/css/bootstrap.min.css";
import "./styles/App.css";
import "./styles/Transitions.css";
import { Route, BrowserRouter } from "react-router-dom";
import Dashboard from "./components/Dashboard";
import Preferences from "./components/Preferences";
import CommandBuilder from "./components/CommandBuilder/CommandBuilder";
import LessonBuilder from "./components/LessonBuilder/LessonBuilder";
import BetaArea from "./components/BetaArea";
import NavBar from "./components/NavBar";
import { getWebSocket, getConfigFunction } from "./services/main";
import Amplify, { Auth } from "aws-amplify";
// file generated by the sls plugin
import config from "./amplify-config";
import { withAuthenticator } from "aws-amplify-react";
import { HTTP_API_URL } from "./utils/Constants";
Amplify.configure({
  Auth: {
    mandatorySignIn: true,
    region: config.cognito.REGION,
    userPoolId: config.cognito.USER_POOL_ID,
    identityPoolId: config.cognito.IDENTITY_POOL_ID,
    userPoolWebClientId: config.cognito.APP_CLIENT_ID,
  },
  API: {
    endpoints: [
      {
        name: "talkbackBE",
        endpoint: HTTP_API_URL,
        region: "eu-west-2",
      },
    ],
  },
});

function App() {
  const [isAuthenticated, userHasAuthenticated] = useState(false);
  useEffect(() => {
    onLoad();
  }, []);

  async function onLoad() {
    try {
      await Auth.currentSession();
      userHasAuthenticated(true);
    } catch (e) {
      if (e !== "No current user") {
        alert(e);
      }
    }

    // setIsAuthenticating(false);
    const user = await Auth.currentUserPoolUser();
    console.log(user.username);
  }
  return (
    <Fragment>
      {isAuthenticated}
      <BrowserRouter>
        <NavBar />
        <Route path="/dashboard" component={Dashboard} />
        <Route
          path="/prefs"
          render={() => (
            <Preferences
              ref={(Preferences) => {
                window.Preferences = Preferences;
              }}
            />
          )}
        />
        <Route
          path="/commands"
          render={(props) => (
            <CommandBuilder
              {...props}
              ws={getWebSocket()}
              getConfig={getConfigFunction}
            />
          )}
        />
        <Route path="/lessons" component={LessonBuilder} />
        <Route
          path="/beta"
          render={(props) => (
            <BetaArea
              {...props}
              ws={getWebSocket()}
              getConfig={getConfigFunction}
            />
          )}
        />
      </BrowserRouter>
    </Fragment>
  );
}

export default withAuthenticator(App, true);
